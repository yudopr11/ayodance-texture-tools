namespace acv {
// Preserve the full ID in callee-saved ESI after pushing the node; never widen the adjacent filename slot.
inline constexpr uintptr_t archive_cache_patch_address = 0x005ab1abu;
inline constexpr uint8_t archive_cache_before[] = {
    0x8a,0x46,0x10,0xb9,0x60,0xa0,0xc2,0x03,0x56,0x88,0x85,0xef,0xfc,0xff,0xff,
    0xe8,0xe1,0x5a,0xe8,0xff,0x6a,0x18,0x50,0xe8,0xa1,0x49,0x71,0x00,
    0x0f,0xb6,0xb5,0xef,0xfc,0xff,0xff,0x83,0xc4,0x08
};
inline constexpr uint8_t archive_cache_after[] = {
    0x8a,0x46,0x10,0xb9,0x60,0xa0,0xc2,0x03,0x56,0x8b,0x76,0x10,0x90,0x90,0x90,
    0xe8,0xe1,0x5a,0xe8,0xff,0x6a,0x18,0x50,0xe8,0xa1,0x49,0x71,0x00,
    0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x83,0xc4,0x08
};
static_assert(sizeof(archive_cache_before) == sizeof(archive_cache_after));
inline constexpr uint8_t archive_erase_entry[] = {0x55,0x8b,0xec,0x83,0xec,0x08,0x8b,0x45,0x08,0x53,0x56,0x8b,0xd9,0x89,0x45,0xfc};
inline constexpr uint8_t archive_erase_exit[] = {0x5e,0x5b,0x8b,0xe5,0x5d,0xc2,0x04,0x00};
inline constexpr uint8_t archive_sized_release[] = {0x55,0x8b,0xec,0xff,0x75,0x08,0xe8,0x6b,0,0,0,0x59,0x5d,0xc3};
inline bool archive_cache_ready(uint32_t count,const void* site,const void* entry,const void* exit,const void* release) {
    return count == 0 && !memcmp(site,archive_cache_before,sizeof archive_cache_before) &&
        !memcmp(entry,archive_erase_entry,sizeof archive_erase_entry) &&
        !memcmp(exit,archive_erase_exit,sizeof archive_erase_exit) &&
        !memcmp(release,archive_sized_release,sizeof archive_sized_release);
}
} // namespace acv
